// Generates ShedIcons.kt from the MingCute icons the web UI uses (src/lib/components/Icon.svelte), so both use the same set.
// Run from the repo root: bun android/scripts/icons.ts
import { readFileSync, writeFileSync } from 'node:fs';

const svelte = readFileSync('src/lib/components/Icon.svelte', 'utf8');
const imports = Object.fromEntries([...svelte.matchAll(/import (\w+) from '@mingcute\/svelte\/(core-[\w-]+)\/([\w-]+)';/g)].map((m) => [m[1], `${m[2]}/${m[3]}`]));
const names = [...svelte.slice(svelte.indexOf('const ICONS')).matchAll(/^\s+'?([\w-]+)'?: (\w+),?$/gm)].map((m) => [m[1], m[2]] as const);

type El = { tag: string; attributes: Record<string, string> };
const KEYWORDS = new Set(['package', 'as', 'break', 'class', 'continue', 'do', 'else', 'false', 'for', 'fun', 'if', 'in', 'interface', 'is', 'null', 'object', 'return', 'super', 'this', 'throw', 'true', 'try', 'typealias', 'typeof', 'val', 'var', 'when', 'while']);
const camel = (s: string) => {
	const n = s.replace(/-(\w)/g, (_, c) => c.toUpperCase());
	return KEYWORDS.has(n) ? `\`${n}\`` : n;
};
const path = (a: Record<string, string>) => {
	if (a.d) return a.d;
	throw new Error('only paths are supported');
};
const out: string[] = [];
for (const [name, v] of names) {
	const file = `node_modules/@mingcute/icons/dist/styles/${imports[v]}.js`;
	const src = readFileSync(file, 'utf8');
	const icon = JSON.parse(src.slice(src.indexOf('{'), src.lastIndexOf('}') + 1).replace(/;\s*export.*$/s, '')) as { elements: El[] };
	const paths = icon.elements.map((e) => {
		const a = e.attributes;
		const stroke = a.stroke === 'currentColor';
		return `\t\tpath(${JSON.stringify(path(a))}, stroke = ${stroke}, fill = ${a.fill === 'currentColor' || (!stroke && a.fill !== 'none')}, width = ${a['stroke-width'] ?? 0}f, round = ${a['stroke-linecap'] === 'round'}, evenOdd = ${a['fill-rule'] === 'evenodd'})`;
	});
	out.push(`\tval ${camel(name)}: ImageVector by lazy {\n\t\ticon("${name}") {\n${paths.join('\n').replace(/^\t\t/gm, '\t\t\t')}\n\t\t}\n\t}`);
}
const kt = `// Generated by android/scripts/icons.ts from MingCute (Apache-2.0), the set the web UI uses. Don't edit by hand.
package dev.shed.app.ui

import androidx.compose.ui.graphics.PathFillType
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

object ShedIcons {
	private class B(val b: ImageVector.Builder) {
		fun path(d: String, stroke: Boolean, fill: Boolean, width: Float, round: Boolean, evenOdd: Boolean) {
			b.addPath(
				pathData = addPathNodes(d),
				pathFillType = if (evenOdd) PathFillType.EvenOdd else PathFillType.NonZero,
				fill = if (fill) SolidColor(Color.Black) else null,
				stroke = if (stroke) SolidColor(Color.Black) else null,
				strokeLineWidth = width,
				strokeLineCap = if (round) StrokeCap.Round else StrokeCap.Butt,
				strokeLineJoin = if (round) StrokeJoin.Round else StrokeJoin.Miter
			)
		}
	}

	private fun icon(name: String, block: B.() -> Unit) = ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f).also { B(it).block() }.build()

${out.join('\n\n')}
}
`;
writeFileSync('android/app/src/main/kotlin/dev/shed/app/ui/ShedIcons.kt', kt);
console.log(`${names.length} icons`);
